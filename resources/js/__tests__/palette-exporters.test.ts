import { describe, expect, it } from 'vitest';
import {
    PALETTE_ALGORITHM_VERSION,
    PALETTE_TONES,
    buildPaletteScale,
    formatHex,
    parseColor,
    type Rgba,
} from '@/lib/color';
import { PALETTE_ROLES, PALETTE_THEMES } from '@/lib/palettePayload';
import {
    PALETTE_EXPORT_FORMATS,
    buildAllExports,
    buildPaletteExport,
    sanitizePaletteName,
    type PaletteExportFormat,
} from '@/tools/palette-generator/lib/exporters';
import { COLOR_TOKEN_FORMAT_VERSION } from '@/tools/palette-generator/lib/tokenExporters';
import type { PaletteRoleColors, PaletteRoles } from '@/types/colors';

/**
 * Exportadores da F2.
 *
 * O shape de cada arquivo e contrato publico (o usuario baixa e cola no
 * projeto), entao os testes conferem linha a linha e nao so "contem".
 */

function colorOf(input: string): Rgba {
    const parsed = parseColor(input);

    if (!parsed.ok) {
        throw new Error(`cor de teste invalida: ${input}`);
    }

    return parsed.color.rgba;
}

const INDIGO = colorOf('#6366f1');
const SCALE = buildPaletteScale(INDIGO);
const ALPHA_SCALE = buildPaletteScale({ ...INDIGO, a: 0.5 });

function linesOf(contents: string): string[] {
    return contents.split('\n');
}

function variablesOf(contents: string, prefix: string): string[] {
    return linesOf(contents).filter((line) => line.includes(prefix));
}

const EXPECTED_FILE: Record<
    PaletteExportFormat,
    { filename: string; mime: string }
> = {
    css: { filename: 'primary.css', mime: 'text/css;charset=utf-8' },
    scss: { filename: 'primary.scss', mime: 'text/x-scss;charset=utf-8' },
    json: {
        filename: 'primary.json',
        mime: 'application/json;charset=utf-8',
    },
    dtcg: {
        filename: 'primary.tokens.json',
        mime: 'application/json;charset=utf-8',
    },
    'style-dictionary': {
        filename: 'primary.style-dictionary.json',
        mime: 'application/json;charset=utf-8',
    },
    typescript: {
        filename: 'primary.tokens.ts',
        mime: 'text/typescript;charset=utf-8',
    },
    'tailwind-v3': {
        filename: 'tailwind.primary.config.js',
        mime: 'text/javascript;charset=utf-8',
    },
    'tailwind-v4': {
        filename: 'primary.tailwind.css',
        mime: 'text/css;charset=utf-8',
    },
};

describe('sanitizePaletteName', () => {
    it('normaliza maiusculas, espacos e pontuacao', () => {
        expect(sanitizePaletteName('  Minha Paleta  ')).toBe('minha-paleta');
        expect(sanitizePaletteName('Marca & Cores!')).toBe('marca-cores');
    });

    it('remove diacriticos', () => {
        expect(sanitizePaletteName('Ação')).toBe('acao');
        expect(sanitizePaletteName('Coração')).toBe('coracao');
    });

    it('colapsa e apara separadores', () => {
        expect(sanitizePaletteName('--muitos---hifens--')).toBe('muitos-hifens');
    });

    it('cai no fallback quando nao sobra nada', () => {
        expect(sanitizePaletteName('')).toBe('primary');
        expect(sanitizePaletteName('   ')).toBe('primary');
        expect(sanitizePaletteName('!!!')).toBe('primary');
    });

    it('corta em 32 caracteres sem terminar em hifen', () => {
        const long = 'a'.repeat(30) + ' fim';
        const slug = sanitizePaletteName(long);

        expect(slug).toHaveLength(32);
        expect(slug.endsWith('-')).toBe(false);
    });
});

describe('buildPaletteExport — identificacao do arquivo', () => {
    it('usa nome sanitizado no arquivo e no conteudo', () => {
        const file = buildPaletteExport(SCALE, 'css', ' Minha Paleta! ');

        expect(file.filename).toBe('minha-paleta.css');
        expect(file.contents).toContain('--color-minha-paleta-50:');
        expect(file.contents).toContain(
            '/* minha-paleta - generated by devtools palette generator',
        );
    });

    it('devolve filename e mime de cada formato', () => {
        for (const format of PALETTE_EXPORT_FORMATS) {
            const file = buildPaletteExport(SCALE, format, 'primary');
            const expected = EXPECTED_FILE[format];

            expect(file.format).toBe(format);
            expect(file.filename).toBe(expected.filename);
            expect(file.mime).toBe(expected.mime);
        }
    });
});

describe('buildPaletteExport — valores opacos', () => {
    it('CSS tem comentario, :root e os 11 tons na ordem da tabela', () => {
        const contents = buildPaletteExport(SCALE, 'css', 'primary').contents;
        const lines = linesOf(contents);

        expect(lines[0]).toBe(
            `/* primary - generated by devtools palette generator (algorithm v${PALETTE_ALGORITHM_VERSION}) */`,
        );
        expect(lines[1]).toBe(':root {');
        expect(lines.at(-2)).toBe('}');
        expect(contents.endsWith('\n')).toBe(true);

        const variables = variablesOf(contents, '    --color-primary-');
        const expected = SCALE.tones.map(
            (tone) => `    --color-primary-${tone.tone}: ${tone.hex};`,
        );

        expect(variables).toEqual(expected);
        expect(variables).toHaveLength(PALETTE_TONES.length);
    });

    it('SCSS usa variaveis !default', () => {
        const contents = buildPaletteExport(SCALE, 'scss', 'primary').contents;

        expect(variablesOf(contents, '$color-primary-')).toEqual(
            SCALE.tones.map(
                (tone) => `$color-primary-${tone.tone}: ${tone.hex} !default;`,
            ),
        );
        expect(contents.endsWith('\n')).toBe(true);
    });

    it('JSON e autodescritivo e preserva a ordem das chaves', () => {
        const contents = buildPaletteExport(SCALE, 'json', 'primary').contents;
        const parsed = JSON.parse(contents) as {
            name: string;
            formatVersion: number;
            algorithmVersion: number;
            base: string;
            clippedTones: number[];
            colors: Record<string, string>;
            semantic?: unknown;
        };

        expect(parsed.name).toBe('primary');
        expect(parsed.formatVersion).toBe(COLOR_TOKEN_FORMAT_VERSION);
        expect(parsed.algorithmVersion).toBe(PALETTE_ALGORITHM_VERSION);
        // Aditivo da Etapa 6: a base viaja junto para a importacao fiel.
        expect(parsed.base).toBe(formatHex(SCALE.base));
        expect(parsed.clippedTones).toEqual(SCALE.clippedTones);
        expect(parsed.semantic).toBeUndefined();
        expect(Object.keys(parsed.colors)).toEqual(
            PALETTE_TONES.map(String),
        );

        for (const tone of SCALE.tones) {
            expect(parsed.colors[String(tone.tone)]).toBe(tone.hex);
        }

        expect(contents).toContain('\n  "colors": {');
        expect(contents).toContain('\n    "50": "#');
        expect(contents.endsWith('\n')).toBe(true);
    });

    it('Tailwind v3 aninha a escala em theme.extend.colors', () => {
        const contents = buildPaletteExport(
            SCALE,
            'tailwind-v3',
            'primary',
        ).contents;
        const lines = linesOf(contents);

        expect(lines[0]).toBe('module.exports = {');
        expect(lines[1]).toBe('    theme: {');
        expect(lines[2]).toBe('        extend: {');
        expect(lines[3]).toBe('            colors: {');
        expect(lines[4]).toBe('                primary: {');
        expect(lines.at(-2)).toBe('};');
        expect(contents.endsWith('\n')).toBe(true);

        expect(variablesOf(contents, '                    ')).toEqual(
            SCALE.tones.map((tone) => `                    ${tone.tone}: '${tone.hex}',`),
        );
    });

    it('Tailwind v4 usa o bloco @theme', () => {
        const contents = buildPaletteExport(
            SCALE,
            'tailwind-v4',
            'primary',
        ).contents;
        const lines = linesOf(contents);

        expect(lines[0]).toBe('@theme {');
        expect(lines.at(-2)).toBe('}');
        expect(contents.endsWith('\n')).toBe(true);

        expect(variablesOf(contents, '    --color-primary-')).toEqual(
            SCALE.tones.map(
                (tone) => `    --color-primary-${tone.tone}: ${tone.hex};`,
            ),
        );
    });
});

describe('buildPaletteExport — valores com alpha', () => {
    it('CSS/SCSS/Tailwind v3 usam rgba() com ate 3 casas', () => {
        const scale = buildPaletteScale({ ...INDIGO, a: 0.333 });
        const tone = scale.tones[0];

        if (tone === undefined) {
            throw new Error('tom ausente');
        }

        const rgb = [
            Math.round(tone.rgba.r),
            Math.round(tone.rgba.g),
            Math.round(tone.rgba.b),
        ].join(', ');
        const expected = `rgba(${rgb}, 0.333)`;

        const css = buildPaletteExport(scale, 'css', 'primary').contents;
        const scss = buildPaletteExport(scale, 'scss', 'primary').contents;
        const tailwind = buildPaletteExport(
            scale,
            'tailwind-v3',
            'primary',
        ).contents;

        expect(css).toContain(`--color-primary-50: ${expected};`);
        expect(scss).toContain(`$color-primary-50: ${expected} !default;`);
        expect(tailwind).toContain(`50: '${expected}',`);
        expect(css).not.toContain('#');
    });

    it('alpha limpo perde os zeros a direita', () => {
        const css = buildPaletteExport(ALPHA_SCALE, 'css', 'primary').contents;

        expect(css).toMatch(/--color-primary-50: rgba\(\d+, \d+, \d+, 0\.5\);/);
    });

    it('JSON e Tailwind v4 usam HEX8', () => {
        const json = buildPaletteExport(ALPHA_SCALE, 'json', 'primary').contents;
        const parsed = JSON.parse(json) as {
            base: string;
            colors: Record<string, string>;
        };

        expect(parsed.colors['50']).toMatch(/^#[0-9a-f]{8}$/);
        expect(parsed.colors['50']).toBe(ALPHA_SCALE.tones[0]?.hex);
        // A base tambem preserva o alpha em HEX8.
        expect(parsed.base).toMatch(/^#[0-9a-f]{8}$/);

        const v4 = buildPaletteExport(
            ALPHA_SCALE,
            'tailwind-v4',
            'primary',
        ).contents;

        expect(v4).toMatch(/--color-primary-950: #[0-9a-f]{8};/);
    });
});

describe('buildAllExports', () => {
    it('devolve todos os formatos na ordem canonica', () => {
        const files = buildAllExports(SCALE, 'primary');

        expect(files.map((file) => file.format)).toEqual(
            PALETTE_EXPORT_FORMATS,
        );
        expect(files.map((file) => file.filename)).toEqual(
            PALETTE_EXPORT_FORMATS.map(
                (format) => EXPECTED_FILE[format].filename,
            ),
        );
    });

    it('e deterministico', () => {
        expect(buildAllExports(SCALE, 'primary')).toEqual(
            buildAllExports(SCALE, 'primary'),
        );
    });

    it('nao exporta a cor base como tom', () => {
        const files = buildAllExports(SCALE, 'primary');
        const json = files.find((file) => file.format === 'json');

        if (json === undefined) {
            throw new Error('export json ausente');
        }

        const parsed = JSON.parse(json.contents) as {
            colors: Record<string, string>;
        };

        expect(Object.keys(parsed.colors)).toHaveLength(PALETTE_TONES.length);
    });
});

const LIGHT_ROLES: PaletteRoleColors = {
    primary: '#332211',
    secondary: '#443322',
    accent: '#554433',
    background: '#fefefe',
    surface: '#f5f5f5',
    text: '#111111',
    text_muted: '#555555',
    border: '#dddddd',
};

const DARK_ROLES: PaletteRoleColors = {
    primary: '#aabbcc',
    secondary: '#99aabb',
    accent: '#8899aa',
    background: '#0a0a0a',
    surface: '#151515',
    text: '#fafafa',
    text_muted: '#a0a0a0',
    border: '#333333',
};

const ROLES: PaletteRoles = { light: LIGHT_ROLES, dark: DARK_ROLES };

const SEMANTIC_LINES = PALETTE_THEMES.flatMap((theme) =>
    PALETTE_ROLES.map((role) => `${theme}-${role}`),
);

describe('buildPaletteExport — papeis semanticos', () => {
    it('sem roles, CSS/SCSS/JSON nao ganham a camada semantica', () => {
        const css = buildPaletteExport(SCALE, 'css', 'primary').contents;
        const scss = buildPaletteExport(SCALE, 'scss', 'primary').contents;
        const json = JSON.parse(
            buildPaletteExport(SCALE, 'json', 'primary').contents,
        ) as { semantic?: unknown };

        expect(css).not.toContain('--color-light-');
        expect(scss).not.toContain('$color-light-');
        expect(json.semantic).toBeUndefined();
    });

    it('CSS poe os 8 papeis de cada tema depois das 11 primitivas', () => {
        const css = buildPaletteExport(SCALE, 'css', 'primary', ROLES).contents;
        const variables = variablesOf(css, '    --color-');

        expect(variables).toHaveLength(PALETTE_TONES.length + 16);
        expect(variables.slice(PALETTE_TONES.length)).toEqual(
            SEMANTIC_LINES.map((key) => {
                const separator = key.indexOf('-');
                const theme = key.slice(0, separator) as 'light' | 'dark';
                const role = key.slice(separator + 1) as keyof PaletteRoleColors;

                return `    --color-${key}: ${ROLES[theme][role]};`;
            }),
        );
    });

    it('SCSS usa !default nos papeis', () => {
        const scss = buildPaletteExport(SCALE, 'scss', 'primary', ROLES).contents;

        expect(scss).toContain(
            `$color-light-primary: ${LIGHT_ROLES.primary} !default;`,
        );
        expect(scss).toContain(
            `$color-dark-border: ${DARK_ROLES.border} !default;`,
        );
    });

    it('JSON aninha os papeis por tema', () => {
        const json = JSON.parse(
            buildPaletteExport(SCALE, 'json', 'primary', ROLES).contents,
        ) as { semantic: PaletteRoles };

        expect(json.semantic).toEqual(ROLES);
        expect(Object.keys(json.semantic.light)).toEqual([...PALETTE_ROLES]);
    });

    it('Tailwind continua so com primitivas mesmo com roles', () => {
        for (const format of ['tailwind-v3', 'tailwind-v4'] as const) {
            const contents = buildPaletteExport(
                SCALE,
                format,
                'primary',
                ROLES,
            ).contents;

            expect(contents).not.toContain('light-primary');
            expect(contents).not.toContain('dark-primary');
        }
    });
});
