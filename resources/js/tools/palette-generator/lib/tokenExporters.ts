import { formatHex, formatHex8, type PaletteScale } from '@/lib/color';
import { PALETTE_ROLES, PALETTE_THEMES } from '@/lib/palettePayload';
import type {
    PaletteRole,
    PaletteRoles,
    PaletteTheme,
} from '@/types/colors';

/**
 * Exportacao de design tokens (F5, ADR-095).
 *
 * Primitivas: os 11 tons da escala. Semantica: os 8 papeis de cada tema, que
 * so existem no editor de paletas (ADR-126). Puro: recebe a escala e devolve
 * texto; comentario e rotulo sao neutros de idioma, como nos exporters da F2.
 *
 * O DTCG usa `$type`/`$value` e um namespace proprio em `$extensions` para a
 * versao do formato - chaves que Tokens Studio e Figma Variables ignoram. O
 * Style Dictionary mantem o vocabulario classico (`value`/`type`) e fica sem
 * metadados para nao virar token nem quebrar o v3. Nenhum dos dois fala com a
 * API do Figma: o arquivo e baixado e importado pelo plugin.
 */

/** Versao do contrato de tokens; a importacao (F6) valida este numero. */
export const COLOR_TOKEN_FORMAT_VERSION = 1;

/** Namespace das extensoes DTCG. */
const DTCG_EXTENSION_KEY = 'devtools.colors';

/** Base em HEX6 ou HEX8, conforme o alpha. */
export function baseHex(scale: PaletteScale): string {
    return scale.base.a < 1 ? formatHex8(scale.base) : formatHex(scale.base);
}

/**
 * Nota de gamut para comentario/descricao: o tom vem do OKLCH e o croma que
 * nao cabe no sRGB e cortado preservando L e H.
 */
export function gamutNote(scale: PaletteScale): string {
    if (scale.clippedTones.length === 0) {
        return 'Gamut: tones computed in OKLCH and mapped to sRGB; no chroma clipping.';
    }

    return `Gamut: tones computed in OKLCH and mapped to sRGB; chroma reduced to fit the sRGB gamut on tones ${scale.clippedTones.join(', ')}.`;
}

/**
 * Identificador TypeScript a partir do slug: camelCase + `Tokens`. Slug que
 * comeca com digito nao e identificador valido, entao ganha o prefixo
 * `palette`.
 */
export function tokenIdentifier(slug: string): string {
    const camel = slug
        .split('-')
        .filter((part) => part !== '')
        .map((part, index) =>
            index === 0
                ? part
                : `${part.charAt(0).toUpperCase()}${part.slice(1)}`,
        )
        .join('');

    const safe = /^[0-9]/.test(camel) ? `palette${camel}` : camel;

    return `${safe}Tokens`;
}

/** Arvore `{ light, dark } -> papeis`, na ordem canonica. */
function semanticTree<T>(
    roles: PaletteRoles,
    wrap: (hex: string) => T,
): Record<PaletteTheme, Record<PaletteRole, T>> {
    const tree = {} as Record<PaletteTheme, Record<PaletteRole, T>>;

    for (const theme of PALETTE_THEMES) {
        const group = {} as Record<PaletteRole, T>;

        for (const role of PALETTE_ROLES) {
            group[role] = wrap(roles[theme][role]);
        }

        tree[theme] = group;
    }

    return tree;
}

/** Grupo nativo `{ light: { role: hex } }` usado no JSON de ida e volta. */
export function semanticHexMap(
    roles: PaletteRoles,
): Record<PaletteTheme, Record<PaletteRole, string>> {
    return semanticTree(roles, (hex) => hex);
}

/**
 * W3C DTCG: `color.{slug}.{tom}` com `$type`/`$value` e, com papeis,
 * `color.{slug}.semantic.{tema}.{papel}`. Alpha continua em HEX8.
 */
export function buildDtcgTokens(
    scale: PaletteScale,
    slug: string,
    roles?: PaletteRoles,
): string {
    const group: Record<string, unknown> = {};

    for (const tone of scale.tones) {
        group[String(tone.tone)] = { $type: 'color', $value: tone.hex };
    }

    if (roles !== undefined) {
        group.semantic = semanticTree(roles, (hex) => ({
            $type: 'color',
            $value: hex,
        }));
    }

    const document = {
        $description: `${slug} - generated by devtools palette generator (tokens v${COLOR_TOKEN_FORMAT_VERSION}, algorithm v${scale.algorithmVersion}).`,
        $extensions: {
            [DTCG_EXTENSION_KEY]: {
                formatVersion: COLOR_TOKEN_FORMAT_VERSION,
                algorithmVersion: scale.algorithmVersion,
                name: slug,
                base: baseHex(scale),
                clippedTones: scale.clippedTones,
                gamut: gamutNote(scale),
            },
        },
        color: { [slug]: group },
    };

    return `${JSON.stringify(document, null, 2)}\n`;
}

/** Style Dictionary classico: mesma arvore com `value`/`type`. */
export function buildStyleDictionaryTokens(
    scale: PaletteScale,
    slug: string,
    roles?: PaletteRoles,
): string {
    const group: Record<string, unknown> = {};

    for (const tone of scale.tones) {
        group[String(tone.tone)] = { value: tone.hex, type: 'color' };
    }

    if (roles !== undefined) {
        group.semantic = semanticTree(roles, (hex) => ({
            value: hex,
            type: 'color',
        }));
    }

    return `${JSON.stringify({ color: { [slug]: group } }, null, 2)}\n`;
}

/**
 * TypeScript: um unico objeto `as const` com primitivas e, com papeis, as
 * semanticas. O cabecalho registra versao do formato, algoritmo, base e gamut.
 */
export function buildTypeScriptTokens(
    scale: PaletteScale,
    slug: string,
    roles?: PaletteRoles,
): string {
    const lines = [
        '/**',
        ` * ${slug} - generated by devtools palette generator.`,
        ` * Tokens format v${COLOR_TOKEN_FORMAT_VERSION} - algorithm v${scale.algorithmVersion} - base ${baseHex(scale)}.`,
        ` * ${gamutNote(scale)}`,
        ' */',
        `export const ${tokenIdentifier(slug)} = {`,
        '    color: {',
    ];

    for (const tone of scale.tones) {
        lines.push(`        ${tone.tone}: '${tone.hex}',`);
    }

    if (roles !== undefined) {
        lines.push('        semantic: {');

        for (const theme of PALETTE_THEMES) {
            lines.push(`            ${theme}: {`);

            for (const role of PALETTE_ROLES) {
                lines.push(
                    `                ${role}: '${roles[theme][role]}',`,
                );
            }

            lines.push('            },');
        }

        lines.push('        },');
    }

    lines.push('    },', '} as const;');

    return `${lines.join('\n')}\n`;
}
