import type { PaletteScale, PaletteToneResult } from '@/lib/color';
import { PALETTE_ROLES, PALETTE_THEMES } from '@/lib/palettePayload';
import type { PaletteRoles } from '@/types/colors';
import {
    COLOR_TOKEN_FORMAT_VERSION,
    buildDtcgTokens,
    buildStyleDictionaryTokens,
    buildTypeScriptTokens,
    semanticHexMap,
} from './tokenExporters';

/**
 * Exportacao da escala (F2) e dos design tokens (F5).
 *
 * Puro: recebe a escala pronta e devolve texto. O nome vira identificador
 * (slug) em todos os formatos, entao ele e sanitizado antes de qualquer
 * interpolacao. Nada de i18n aqui: comentario e rotulo sao neutros de idioma.
 *
 * Sem `roles` (o gerador) a saida dos formatos da F2 continua identica; com
 * `roles` (o editor) CSS/SCSS/JSON ganham a camada semantica. Tailwind segue
 * so com primitivas: papeis claro/escuro nao cabem em `theme.colors`.
 */

export type PaletteExportFormat =
    | 'css'
    | 'scss'
    | 'json'
    | 'dtcg'
    | 'style-dictionary'
    | 'typescript'
    | 'tailwind-v3'
    | 'tailwind-v4';

export interface PaletteExportFile {
    format: PaletteExportFormat;
    filename: string;
    mime: string;
    contents: string;
}

export const PALETTE_EXPORT_FORMATS: PaletteExportFormat[] = [
    'css',
    'scss',
    'json',
    'dtcg',
    'style-dictionary',
    'typescript',
    'tailwind-v3',
    'tailwind-v4',
];

const FALLBACK_NAME = 'primary';
const MAX_NAME_LENGTH = 32;

/**
 * Nome livre -> identificador estavel: minúsculas, sem diacriticos, separado
 * por hifen, no maximo 32 caracteres. Vazio (ou so simbolos) vira `primary`.
 */
export function sanitizePaletteName(raw: string): string {
    const slug = raw
        .normalize('NFD')
        .replace(/\p{M}+/gu, '')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
        .slice(0, MAX_NAME_LENGTH)
        .replace(/-+$/, '');

    return slug === '' ? FALLBACK_NAME : slug;
}

/** Alpha com ate 3 casas e sem zeros a direita. */
function formatAlpha(alpha: number): string {
    return String(Number(alpha.toFixed(3)));
}

/** Valor para CSS/SCSS/Tailwind v3: HEX opaco ou `rgba()`. */
function cssValue(tone: PaletteToneResult): string {
    if (tone.rgba.a >= 1) {
        return tone.hex;
    }

    const red = Math.round(tone.rgba.r);
    const green = Math.round(tone.rgba.g);
    const blue = Math.round(tone.rgba.b);

    return `rgba(${red}, ${green}, ${blue}, ${formatAlpha(tone.rgba.a)})`;
}

function variableLines(
    scale: PaletteScale,
    name: string,
    prefix: string,
    suffix: string,
    indent: string,
    value: (tone: PaletteToneResult) => string = cssValue,
): string[] {
    return scale.tones.map(
        (tone) =>
            `${indent}${prefix}${name}-${tone.tone}: ${value(tone)}${suffix}`,
    );
}

/** Papeis por tema, na ordem canonica: `--color-light-primary` etc. */
function semanticVariableLines(
    roles: PaletteRoles,
    prefix: string,
    suffix: string,
    indent: string,
): string[] {
    return PALETTE_THEMES.flatMap((theme) =>
        PALETTE_ROLES.map(
            (role) =>
                `${indent}${prefix}${theme}-${role}: ${roles[theme][role]}${suffix}`,
        ),
    );
}

function buildCss(
    scale: PaletteScale,
    name: string,
    roles?: PaletteRoles,
): string {
    const lines = [
        `/* ${name} - generated by devtools palette generator (algorithm v${scale.algorithmVersion}) */`,
        ':root {',
        ...variableLines(scale, name, '--color-', ';', '    '),
        ...(roles === undefined
            ? []
            : semanticVariableLines(roles, '--color-', ';', '    ')),
        '}',
    ];

    return `${lines.join('\n')}\n`;
}

function buildScss(
    scale: PaletteScale,
    name: string,
    roles?: PaletteRoles,
): string {
    const lines = [
        ...variableLines(scale, name, '$color-', ' !default;', ''),
        ...(roles === undefined
            ? []
            : semanticVariableLines(roles, '$color-', ' !default;', '')),
    ];

    return `${lines.join('\n')}\n`;
}

function buildJson(
    scale: PaletteScale,
    name: string,
    roles?: PaletteRoles,
): string {
    const colors = Object.fromEntries(
        scale.tones.map((tone) => [String(tone.tone), tone.hex]),
    );

    const document: Record<string, unknown> = {
        name,
        formatVersion: COLOR_TOKEN_FORMAT_VERSION,
        algorithmVersion: scale.algorithmVersion,
        clippedTones: scale.clippedTones,
        colors,
    };

    if (roles !== undefined) {
        document.semantic = semanticHexMap(roles);
    }

    return `${JSON.stringify(document, null, 2)}\n`;
}

function buildTailwindV3(scale: PaletteScale, name: string): string {
    const lines = [
        'module.exports = {',
        '    theme: {',
        '        extend: {',
        '            colors: {',
        `                ${name}: {`,
        ...scale.tones.map(
            (tone) => `                    ${tone.tone}: '${cssValue(tone)}',`,
        ),
        '                },',
        '            },',
        '        },',
        '    },',
        '};',
    ];

    return `${lines.join('\n')}\n`;
}

function buildTailwindV4(scale: PaletteScale, name: string): string {
    const lines = [
        '@theme {',
        // Tailwind v4 aceita HEX8 direto na variavel; mantem o valor sem
        // funcao `rgba()` para o `@theme` ficar declarativo.
        ...variableLines(scale, name, '--color-', ';', '    ', (tone) => tone.hex),
        '}',
    ];

    return `${lines.join('\n')}\n`;
}

export function buildPaletteExport(
    scale: PaletteScale,
    format: PaletteExportFormat,
    rawName: string,
    roles?: PaletteRoles,
): PaletteExportFile {
    const name = sanitizePaletteName(rawName);

    switch (format) {
        case 'css':
            return {
                format,
                filename: `${name}.css`,
                mime: 'text/css;charset=utf-8',
                contents: buildCss(scale, name, roles),
            };
        case 'scss':
            return {
                format,
                filename: `${name}.scss`,
                mime: 'text/x-scss;charset=utf-8',
                contents: buildScss(scale, name, roles),
            };
        case 'json':
            return {
                format,
                filename: `${name}.json`,
                mime: 'application/json;charset=utf-8',
                contents: buildJson(scale, name, roles),
            };
        case 'dtcg':
            return {
                format,
                filename: `${name}.tokens.json`,
                mime: 'application/json;charset=utf-8',
                contents: buildDtcgTokens(scale, name, roles),
            };
        case 'style-dictionary':
            return {
                format,
                filename: `${name}.style-dictionary.json`,
                mime: 'application/json;charset=utf-8',
                contents: buildStyleDictionaryTokens(scale, name, roles),
            };
        case 'typescript':
            return {
                format,
                filename: `${name}.tokens.ts`,
                mime: 'text/typescript;charset=utf-8',
                contents: buildTypeScriptTokens(scale, name, roles),
            };
        case 'tailwind-v3':
            return {
                format,
                filename: `tailwind.${name}.config.js`,
                mime: 'text/javascript;charset=utf-8',
                contents: buildTailwindV3(scale, name),
            };
        case 'tailwind-v4':
            return {
                format,
                filename: `${name}.tailwind.css`,
                mime: 'text/css;charset=utf-8',
                contents: buildTailwindV4(scale, name),
            };
    }
}

export function buildAllExports(
    scale: PaletteScale,
    rawName: string,
    roles?: PaletteRoles,
): PaletteExportFile[] {
    return PALETTE_EXPORT_FORMATS.map((format) =>
        buildPaletteExport(scale, format, rawName, roles),
    );
}
